import type { HLJSApi, Language } from "highlight.js";

/**
 * DAX — the measure and query language of Power BI, Fabric, and Analysis
 * Services. highlight.js ships no grammar for it under any name, so a `dax`
 * fence renders as grey text without this.
 *
 * Data, not logic: `contains` and literal patterns only. This runs over
 * untrusted model output on every token of a stream, so there is no `eval`, no
 * regex assembled from the input, and nothing here that can do anything but
 * classify spans of text.
 *
 * Case-insensitive, as the language is — a model writing `calculate(` and one
 * writing `CALCULATE(` mean the same function and must render the same way.
 */
